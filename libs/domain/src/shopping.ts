import { listExtras, listItemStates, type Database } from '@simmery/db';
import { and, asc, eq, lt } from 'drizzle-orm';
import { isUuid, throwIfIssues, type FieldIssue } from './errors.js';
import type { WeekEvaluation } from './evaluate-week.js';
import {
  checkWeekKey,
  ensureWeek,
  evaluateSavedWeek,
  snapshotEndedWeeks,
  writeSnapshot,
} from './planning.js';

export interface ShoppingItem {
  ingredientId: string;
  name: string;
  unit: string;
  total: number;
  checked: boolean;
}

export interface ShoppingExtra {
  id: string;
  text: string;
  checked: boolean;
}

export interface ShoppingList {
  weekKey: string;
  /** Week totals per ingredient; leftovers and packs belong to the evaluation only (AE2). */
  items: ShoppingItem[];
  extras: ShoppingExtra[];
}

/** A list change stamped with the client's clock; the newest write per item wins (KTD8). */
export type ListOp = { at: Date } & (
  | { type: 'check'; ingredientId: string; checked: boolean }
  /** `id` is generated by the client so later ops can refer to an extra added offline. */
  | { type: 'addExtra'; id: string; text: string }
  | { type: 'renameExtra'; id: string; text: string }
  | { type: 'checkExtra'; id: string; checked: boolean }
  | { type: 'removeExtra'; id: string }
);

async function buildList(
  db: Database,
  userId: string,
  week: { id: string; weekKey: string },
  evaluation: WeekEvaluation,
): Promise<ShoppingList> {
  const [states, extras] = await Promise.all([
    db
      .select({ ingredientId: listItemStates.ingredientId, checked: listItemStates.checked })
      .from(listItemStates)
      .where(and(eq(listItemStates.userId, userId), eq(listItemStates.weekPlanId, week.id))),
    db
      .select({ id: listExtras.id, text: listExtras.text, checked: listExtras.checked })
      .from(listExtras)
      .where(and(eq(listExtras.userId, userId), eq(listExtras.weekPlanId, week.id)))
      .orderBy(asc(listExtras.createdAt), asc(listExtras.id)),
  ]);
  const checked = new Set(
    states.filter((state) => state.checked).map((state) => state.ingredientId),
  );
  return {
    weekKey: week.weekKey,
    items: evaluation.lines.map(({ ingredientId, name, unit, total }) => ({
      ingredientId,
      name,
      unit,
      total,
      checked: checked.has(ingredientId),
    })),
    extras,
  };
}

export async function getShoppingList(
  db: Database,
  userId: string,
  weekKey: string,
  now: Date = new Date(),
): Promise<ShoppingList> {
  checkWeekKey(weekKey);
  await snapshotEndedWeeks(db, userId, now);
  const week = await ensureWeek(db, userId, weekKey);
  return buildList(db, userId, week, await evaluateSavedWeek(db, userId, week.id));
}

function opIssues(ops: readonly ListOp[]): FieldIssue[] {
  const issues: FieldIssue[] = [];
  ops.forEach((op, index) => {
    if ((op.type === 'addExtra' || op.type === 'renameExtra') && !op.text.trim()) {
      issues.push({ field: `ops[${index}].text`, message: 'must not be empty' });
    }
    if (op.type === 'addExtra' && !isUuid(op.id)) {
      issues.push({ field: `ops[${index}].id`, message: 'must be a UUID' });
    }
    if (!(op.at instanceof Date) || Number.isNaN(op.at.getTime())) {
      issues.push({ field: `ops[${index}].at`, message: 'must be a valid timestamp' });
    }
  });
  return issues;
}

/**
 * Applies list ops last-write-wins per item by client timestamp, so arrival order does
 * not matter (KTD8). Ops on items no longer on the list are ignored. The first applied
 * check-off writes the week's snapshot (KTD13).
 */
export async function applyListOps(
  db: Database,
  userId: string,
  weekKey: string,
  ops: readonly ListOp[],
  now: Date = new Date(),
): Promise<ShoppingList> {
  checkWeekKey(weekKey);
  throwIfIssues(opIssues(ops));
  const week = await ensureWeek(db, userId, weekKey);

  const evaluation = await db.transaction(async (tx) => {
    const evaluation = await evaluateSavedWeek(tx, userId, week.id);
    const onList = new Set(evaluation.lines.map((line) => line.ingredientId));
    const ordered = [...ops].sort((a, b) => a.at.getTime() - b.at.getTime());
    let checkedOff = false;

    for (const op of ordered) {
      const at = op.at > now ? now : op.at;
      if (op.type === 'check') {
        if (!onList.has(op.ingredientId)) {
          continue;
        }
        const applied = await tx
          .insert(listItemStates)
          .values({
            userId,
            weekPlanId: week.id,
            ingredientId: op.ingredientId,
            checked: op.checked,
            clientUpdatedAt: at,
          })
          .onConflictDoUpdate({
            target: [listItemStates.weekPlanId, listItemStates.ingredientId],
            set: { checked: op.checked, clientUpdatedAt: at },
            setWhere: lt(listItemStates.clientUpdatedAt, at),
          })
          .returning({ ingredientId: listItemStates.ingredientId });
        checkedOff ||= applied.length > 0;
        continue;
      }
      if (!isUuid(op.id)) {
        continue;
      }
      const ownExtra = and(
        eq(listExtras.id, op.id),
        eq(listExtras.userId, userId),
        eq(listExtras.weekPlanId, week.id),
        lt(listExtras.clientUpdatedAt, at),
      );
      switch (op.type) {
        case 'addExtra': {
          const text = op.text.trim();
          await tx
            .insert(listExtras)
            .values({
              id: op.id,
              userId,
              weekPlanId: week.id,
              text,
              clientUpdatedAt: at,
              createdAt: at,
            })
            .onConflictDoUpdate({
              target: listExtras.id,
              set: { text, clientUpdatedAt: at },
              setWhere: ownExtra,
            });
          break;
        }
        case 'renameExtra':
          await tx
            .update(listExtras)
            .set({ text: op.text.trim(), clientUpdatedAt: at })
            .where(ownExtra);
          break;
        case 'checkExtra': {
          const applied = await tx
            .update(listExtras)
            .set({ checked: op.checked, clientUpdatedAt: at })
            .where(ownExtra)
            .returning({ id: listExtras.id });
          checkedOff ||= applied.length > 0;
          break;
        }
        case 'removeExtra':
          await tx.delete(listExtras).where(ownExtra);
          break;
      }
    }

    if (checkedOff) {
      await writeSnapshot(tx, userId, week.id, evaluation);
    }
    return evaluation;
  });
  return buildList(db, userId, week, evaluation);
}
